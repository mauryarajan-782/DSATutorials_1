package DSATutorials;

public class SwappingTwoNumbers {

	public static void main(String[] args) {
		
		int no1 = 10;		//assignment statement
		int no2 = 20;		//assignment statement
		
		int temp = no1;		//assignment statement
		no1 = no2;			//assignment statement
		no2 =  temp;		//assignment statement
		
		System.out.println("no1 : "+no1);		//print statement
		System.out.println("no2 : "+no2);		//print statement
	}

}

